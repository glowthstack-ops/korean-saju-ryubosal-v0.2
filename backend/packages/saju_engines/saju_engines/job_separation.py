"""직장 이탈 계열 판정 — 해고·퇴사 통보·권고사직을 한 계열로 본다 (2026-10-13 데굴님 지시).

실로그: "오늘 해고통보를 받았어. 앞으로 어떻게 하면 좋을까"가 직업 질문으로 인식되지 않아
'오늘 하루 운세'로 답했고, '오늘'을 빼면 너무 넓은 질문으로 반려됐다. 해고·퇴사 통보·권고사직·
정리해고·구조조정·희망퇴직·실직은 모두 **직장을 떠나게 된 사건**이라는 같은 계열이다.

이 모듈 하나를 파서(직업 도메인·이직/직업 변화 사건), 답변 지평(구조 결정형), 사용자 사실 원장,
답변 지시가 함께 쓴다 — 어휘를 여러 곳에 흩어 두면 한쪽만 갱신되는 결함이 생긴다.
규칙 기반이며 LLM 판정을 쓰지 않는다(절대원칙 1).
"""

from __future__ import annotations

import re

#: 직장 이탈 계열 어휘. '잘렸/짤렸'은 '머리 잘렸어'와 동형이라 회사·직장·일자리와 붙은 경우만,
#: '퇴사'는 '통보'와 붙은 경우만(퇴사 단독은 기존 직업 도메인 어휘가 이미 잡는다) 인정한다.
JOB_SEPARATION_RE = re.compile(
    r"해고|권고\s*사직|정리\s*해고|구조\s*조정|희망\s*퇴직|실직|실업"
    r"|퇴사\s*(?:통보|권고|권유|요구)"
    r"|(?:회사|직장|일자리|일터)(?:에서|에서도|에서는)?\s*(?:잘렸|짤렸|잘림|짤림|쫓겨났|나가라)"
)


def is_job_separation(text: str) -> bool:
    """직장 이탈 계열(해고·퇴사 통보·권고사직 등) 사건을 말하는가."""
    return bool(JOB_SEPARATION_RE.search(text or ""))
